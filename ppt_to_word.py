from pptx import Presentation  # 讀取PPT
from docx import Document      # 產生Word
import re                      # 用來清除非法字元
from docx.shared import Pt, RGBColor  # 控制字體大小與顏色

# ==========================================================
# 函式：clean_xml_text
# 功能：
#   清除 Word / XML 不接受的控制字元
# 原因：
#   PowerPoint 備忘稿有時會混入 NULL byte 或其他控制字元，
#   python-docx 寫入時會報錯：
#   ValueError: All strings must be XML compatible
# ==========================================================
def clean_xml_text(text):
    # 如果是 None，轉成空字串，避免後續處理出錯
    if text is None:
        return ""

    # 移除 XML 不允許的控制字元
    # 保留：
    # \x09 = Tab
    # \x0A = 換行
    # \x0D = 回車
    text = re.sub(r'[\x00-\x08\x0B\x0C\x0E-\x1F]', '', text)

    return text


# ==========================================================
# 載入PPT檔案
# 說明：
#   使用 raw string（r"..."）避免 Windows 路徑中的 \ 被誤判
# ==========================================================
ppt_path = r"I:\LearningTime\中央大學文件\資料庫系統專題實作\0330-K線型態、成交量、高低檔、KD指標 有備忘稿版.pptx"

# 讀取 PowerPoint 檔案
prs = Presentation(ppt_path)

# ==========================================================
# 建立 Word 文件
# ==========================================================
doc = Document()

# ==========================================================
# 文件最上方加入總標題
# 這裡也順便設定樣式，讓整份文件看起來更一致
# ==========================================================
title_paragraph = doc.add_paragraph()
title_run = title_paragraph.add_run("PowerPoint 備忘稿匯出")
title_run.bold = True
title_run.font.size = Pt(16)

# ==========================================================
# 遍歷每一頁投影片
# enumerate(prs.slides)：
#   會依序取得每一張投影片
# i + 1：
#   因為 enumerate 預設從 0 開始，所以要 +1 才符合一般頁數習慣
# ==========================================================
for i, slide in enumerate(prs.slides):
    page_num = i + 1

    # ------------------------------------------------------
    # 預設備忘稿為空字串
    # ------------------------------------------------------
    notes = ""

    # ------------------------------------------------------
    # 如果這一頁有備忘稿頁，就抓出備忘稿文字
    # ------------------------------------------------------
    if slide.has_notes_slide:
        notes = slide.notes_slide.notes_text_frame.text

    # ------------------------------------------------------
    # 清理非法字元
    # 避免 Word 寫入時因 XML 控制字元報錯
    # ------------------------------------------------------
    notes = clean_xml_text(notes)

    # ------------------------------------------------------
    # 如果清理完後還是空白，就補上提示文字
    # strip() 的用途：
    #   去掉前後空白、換行、tab
    #   這樣可以判斷是否真的沒有內容
    # ------------------------------------------------------
    if not notes.strip():
        notes = "（無備忘稿）"

    # ------------------------------------------------------
    # 為了讓手機閱讀更清楚，先插入一個空行
    # ------------------------------------------------------
    doc.add_paragraph("")

    # ------------------------------------------------------
    # 建立頁數標題段落
    # 不使用 add_heading()，因為 add_heading() 不好精準控制顏色、粗體、大小
    # 改用 paragraph + run，可以自己指定格式
    # ------------------------------------------------------
    page_paragraph = doc.add_paragraph()

    # 在段落中加入文字內容
    page_run = page_paragraph.add_run(f"第 {page_num} 頁")

    # 設定粗體
    page_run.bold = True

    # 設定字體大小為 14pt
    page_run.font.size = Pt(14)

    # 設定字體顏色為紅色
    page_run.font.color.rgb = RGBColor(255, 0, 0)

    # ------------------------------------------------------
    # 加入備忘稿內容
    # doc.add_paragraph(notes) 會保留字串中的換行效果
    # ------------------------------------------------------
    doc.add_paragraph(notes)

# ==========================================================
# 儲存 Word 檔案
# 注意：
#   副檔名要用 .docx，這才是 Word 正常格式
# ==========================================================
output_path = r"I:\LearningTime\中央大學文件\資料庫系統專題實作\0330-K線型態、成交量、高低檔、KD指標 有備忘稿版_手機閱讀版.docx"
doc.save(output_path)

# ==========================================================
# 在終端機輸出完成訊息
# ==========================================================
print("完成匯出！")
print(f"輸出檔案：{output_path}")