/*======================================================
  練習3：找出KD黃金交叉 / 死亡交叉
  功能：
  1. 指定股票代碼
  2. 指定開始日期與結束日期
  3. 找出該期間內所有KD黃金交叉與死亡交叉
======================================================*/

/*========================================================
Procedure Name : sp_detect_KD_cross

功能：
找出指定股票在指定時間區間內
所有 KD 黃金交叉 與 死亡交叉

輸入參數：
@stock_code   股票代碼
@start_date   查詢開始日期
@end_date     查詢結束日期

輸出：
stock_code
date
result（黃金交叉 / 死亡交叉）

資料來源：
dbo.stock_data
========================================================*/


--------------------------------------------------------
-- 如果資料庫中已經存在此Procedure
-- 先刪除舊版本，避免建立時發生衝突
--------------------------------------------------------
IF OBJECT_ID('sp_detect_KD_cross', 'P') IS NOT NULL
DROP PROCEDURE sp_detect_KD_cross;
GO


--------------------------------------------------------
-- 建立 Stored Procedure
--------------------------------------------------------
CREATE PROCEDURE sp_detect_KD_cross

    ----------------------------------------------------
    -- 宣告輸入參數
    ----------------------------------------------------
    @stock_code VARCHAR(10),   -- 股票代碼
    @start_date DATE,          -- 查詢開始日期
    @end_date   DATE           -- 查詢結束日期

AS
BEGIN


    /*====================================================
      使用CTE (Common Table Expression)
      先整理資料，取得「昨天的K值與D值」
    ====================================================*/
    WITH KD_data AS
    (
        SELECT
            stock_code,     -- 股票代碼
            date,           -- 日期

            K_value,        -- 今日K值
            D_value,        -- 今日D值


            /*------------------------------------------------
              LAG(K_value)

              功能：
              取得「同一檔股票前一天的K值」

              PARTITION BY stock_code
              代表每一檔股票分開計算

              ORDER BY date
              依日期排序，才能判斷誰是前一天
            ------------------------------------------------*/
            LAG(K_value) OVER
            (
                PARTITION BY stock_code
                ORDER BY date
            ) AS yesterday_K,


            /*------------------------------------------------
              LAG(D_value)

              取得「同一檔股票前一天的D值」
            ------------------------------------------------*/
            LAG(D_value) OVER
            (
                PARTITION BY stock_code
                ORDER BY date
            ) AS yesterday_D


        ----------------------------------------------------
        -- 資料來源：已經計算好KD值的資料表
        ----------------------------------------------------
        FROM dbo.stock_data
    )


    /*====================================================
      從整理好的KD_data中判斷交叉
    ====================================================*/
    SELECT

        stock_code,   -- 股票代碼

        date,         -- 發生交叉的日期


        /*--------------------------------------------------
          使用CASE判斷交叉種類
        --------------------------------------------------*/
        CASE

            ------------------------------------------------
            -- 黃金交叉條件
            -- 昨天K <= 昨天D
            -- 今天K > 今天D
            ------------------------------------------------
            WHEN yesterday_K <= yesterday_D
            AND K_value > D_value
            THEN '黃金交叉'


            ------------------------------------------------
            -- 死亡交叉條件
            -- 昨天K >= 昨天D
            -- 今天K < 今天D
            ------------------------------------------------
            WHEN yesterday_K >= yesterday_D
            AND K_value < D_value
            THEN '死亡交叉'

        END AS result


    FROM KD_data


    /*====================================================
      篩選條件
    ====================================================*/
    WHERE stock_code = @stock_code          -- 指定股票

    AND date BETWEEN @start_date AND @end_date   -- 指定查詢期間


    /*----------------------------------------------------
      只保留真的發生交叉的資料
    ----------------------------------------------------*/
    AND
    (
        (yesterday_K <= yesterday_D AND K_value > D_value)
        OR
        (yesterday_K >= yesterday_D AND K_value < D_value)
    )


    ------------------------------------------------------
    -- 依日期排序
    ------------------------------------------------------
    ORDER BY date

END
GO

EXEC sp_detect_KD_cross '2330','2023-09-01','2023-12-01'